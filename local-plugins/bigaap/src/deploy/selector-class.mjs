/**
 * Selector classification for deploy safety.
 *
 * A selector is not deploy-safe because it worked twice. Two captures of the
 * same build agree by construction — the identifiers in them were emitted by
 * the same compilation. Deploy safety is a claim about a DIFFERENT build, and
 * it can only be earned by evidence that does not depend on what that build
 * chose to name things.
 *
 * This module answers the narrower question a classifier can answer alone:
 * what KIND of thing is this selector built from? Whether it actually survived
 * a rebuild is measured separately, in match.mjs, against a second build.
 */

export const SELECTOR_CLASS = {
  /** Element semantics or ARIA: `main`, `nav`, `[role='navigation']`. Survives any rebuild that keeps the meaning. */
  SEMANTIC_STABLE: "semantic-stable",
  /** An author-controlled hook: `[data-testid]`, `[data-component]`, a readable id or class the project maintains. */
  PROJECT_STABLE: "project-stable",
  /** Structure with no name: `main > section > article`. Survives renaming, not restructuring. */
  STRUCTURAL_STABLE: "structural-stable",
  /** Contains a build-generated identifier. Valid until the next deploy. */
  GENERATED: "generated",
  /** Depends on DOM position: `:nth-of-type`, `:nth-child`, `:first-child`. Survives neither reorder nor insertion. */
  POSITIONAL: "positional",
  /** Utility classes that describe presentation and discriminate poorly. */
  UTILITY_NONDISCRIMINATING: "utility-nondiscriminating",
  /** Not enough information to place it. */
  UNKNOWN: "unknown"
};

/** Classes that are deploy-safe hooks by convention rather than by accident. */
const PROJECT_ATTRS = /\[(data-testid|data-test|data-component|data-qa|data-cy|data-id|itemprop)\b/;
/** Any data attribute is author-controlled, but framework markers are not identity. */
const FRAMEWORK_ATTRS = /\[(data-nimg|data-astro-cid[\w-]*|data-reactroot|data-svelte[\w-]*|data-v-[0-9a-f]+|data-n-head)\b/;

const SEMANTIC_TAGS = new Set([
  "main", "nav", "header", "footer", "aside", "article", "section", "form",
  "table", "thead", "tbody", "figure", "figcaption", "dialog", "details",
  "summary", "fieldset", "legend", "h1", "h2", "h3", "h4", "h5", "h6"
]);

const POSITIONAL = /:nth-of-type\(|:nth-child\(|:first-child|:last-child|:first-of-type|:last-of-type|:nth-last-/;

/**
 * Splits a selector into the parts a classification can reason about, without
 * pretending to be a CSS parser: classes, attributes, ids, tags, pseudos.
 */
export function parseSelector(selector) {
  const s = String(selector ?? "");
  return {
    classes: (s.match(/\.[^\s.>+~,[\]()]+(?:\([^)]*\)|\[[^\]]*\])?/g) || []).map((c) => c.slice(1)),
    attributes: s.match(/\[[^\]]*\]/g) || [],
    ids: (s.match(/#[^\s.>+~,[\]()]+/g) || []).map((i) => i.slice(1)),
    tags: (s.match(/(?:^|[\s>+~])([a-z][a-z0-9]*)/g) || []).map((t) => t.trim().replace(/^[>+~]\s*/, "")),
    hasPositional: POSITIONAL.test(s),
    segments: s.split(/\s*>\s*/).filter(Boolean).length
  };
}

/**
 * Classifies a selector.
 *
 * `classify` is the extractor's own class classifier, passed in rather than
 * imported, because it lives in a browser script. Callers that have no
 * classifier get `unknown` for anything class-based, which is the honest
 * answer rather than a guess.
 *
 * Order matters, and it is worst-first: a selector containing one generated
 * class is generated, however much semantic material surrounds it. The reason
 * it fails is the reason a reader needs.
 */
export function classifySelector(selector, { classify = null, volatileIds = null } = {}) {
  if (!selector) return { class: SELECTOR_CLASS.UNKNOWN, reasons: ["no selector"], deploySafe: false };

  const parsed = parseSelector(selector);
  const reasons = [];

  const kindOf = (name) => (classify ? classify(name) : "unknown");
  const generatedClasses = parsed.classes.filter((c) => kindOf(c) === "hashed");
  const utilityClasses = parsed.classes.filter((c) => kindOf(c) === "utility");
  const readableClasses = parsed.classes.filter((c) => kindOf(c) === "readable");

  /* A volatile id is generated by the runtime — `:r1a:` from React useId,
   * `radix-:R2:`, a uuid. It is an id, so it looks maximally specific, and it
   * is gone on the next render. */
  const volatile = parsed.ids.filter((id) => isVolatileId(id, volatileIds));

  if (generatedClasses.length) {
    reasons.push(`build-generated class: ${generatedClasses.join(", ")}`);
    return { class: SELECTOR_CLASS.GENERATED, reasons, deploySafe: false, parsed };
  }
  if (volatile.length) {
    reasons.push(`volatile id: ${volatile.join(", ")}`);
    return { class: SELECTOR_CLASS.GENERATED, reasons, deploySafe: false, parsed };
  }
  if (utilityClasses.length) {
    reasons.push(`utility class, describes presentation not identity: ${utilityClasses.join(", ")}`);
    return { class: SELECTOR_CLASS.UTILITY_NONDISCRIMINATING, reasons, deploySafe: false, parsed };
  }

  /* Author-controlled hooks outrank everything below: a `data-testid` exists
   * precisely so it can be depended on. Framework markers do not count — they
   * identify a renderer, not a component. */
  const projectAttrs = parsed.attributes.filter((a) => PROJECT_ATTRS.test(a));
  const frameworkAttrs = parsed.attributes.filter((a) => FRAMEWORK_ATTRS.test(a));
  if (projectAttrs.length) {
    reasons.push(`author-controlled hook: ${projectAttrs.join(", ")}`);
    /* An anchored selector may still reach its target by position. That does
     * not make it positional — the rejection rule is position ALONE, and this
     * one is findable without counting siblings from the document root — but it
     * is a weaker claim than a fully hook-identified selector, and burying the
     * difference would overstate what the anchor buys. */
    if (parsed.hasPositional) {
      reasons.push(
        "reaches its target positionally from that hook; an element inserted inside the " +
        "component still breaks it"
      );
    }
    return {
      class: SELECTOR_CLASS.PROJECT_STABLE,
      reasons,
      deploySafe: true,
      positionalWithinAnchor: parsed.hasPositional,
      parsed
    };
  }

  if (parsed.hasPositional) {
    reasons.push("depends on DOM position; any inserted sibling changes what it selects");
    return { class: SELECTOR_CLASS.POSITIONAL, reasons, deploySafe: false, parsed };
  }

  const roleAttrs = parsed.attributes.filter((a) => /^\[role=/.test(a));
  const semanticTags = parsed.tags.filter((t) => SEMANTIC_TAGS.has(t));
  if (roleAttrs.length || (semanticTags.length && !readableClasses.length && !frameworkAttrs.length)) {
    reasons.push(
      roleAttrs.length
        ? `ARIA role: ${roleAttrs.join(", ")}`
        : `semantic elements only: ${semanticTags.join(" > ")}`
    );
    return { class: SELECTOR_CLASS.SEMANTIC_STABLE, reasons, deploySafe: true, parsed };
  }

  if (readableClasses.length) {
    reasons.push(`project-maintained class names: ${readableClasses.join(", ")}`);
    return { class: SELECTOR_CLASS.PROJECT_STABLE, reasons, deploySafe: true, parsed };
  }

  if (frameworkAttrs.length) {
    reasons.push(`framework marker, identifies a renderer rather than a component: ${frameworkAttrs.join(", ")}`);
    return { class: SELECTOR_CLASS.UNKNOWN, reasons, deploySafe: false, parsed };
  }

  if (parsed.tags.length) {
    reasons.push("structure and tag names only; survives renaming but not restructuring");
    return { class: SELECTOR_CLASS.STRUCTURAL_STABLE, reasons, deploySafe: true, parsed };
  }

  reasons.push("nothing in this selector identifies what it selects");
  return { class: SELECTOR_CLASS.UNKNOWN, reasons, deploySafe: false, parsed };
}

/**
 * A runtime-generated id.
 *
 * React `useId` emits `:r1:`-style values, Radix emits `radix-:R2h:`, and many
 * frameworks fall back to uuids or counters. All of them change per render or
 * per build, so an id is not automatically a stable hook.
 */
export function isVolatileId(id, extraPattern = null) {
  if (!id) return false;
  if (extraPattern && new RegExp(extraPattern).test(id)) return true;
  if (/^:?[rR][0-9a-z]*:?$/.test(id)) return true;
  if (/^radix-/.test(id)) return true;
  if (/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(id)) return true;
  if (/^(?:headlessui|mantine|mui|chakra|aria)-[a-z0-9-]*\d{3,}/i.test(id)) return true;
  if (/\d{6,}$/.test(id)) return true;
  return false;
}

/**
 * Deploy safety is a claim about a rebuild, so a classification alone cannot
 * establish it. This states what the classification does and does not license.
 */
export function deploySafetyVerdict(classification, { crossBuildEvidence = null } = {}) {
  const base = {
    selectorClass: classification.class,
    classificationAllows: classification.deploySafe,
    reasons: classification.reasons
  };

  if (!classification.deploySafe) {
    return { ...base, verdict: "rejected", proven: false,
      note: "Rejected on classification alone; no cross-build evidence needed." };
  }
  if (!crossBuildEvidence) {
    return { ...base, verdict: "unproven", proven: false,
      note: "The selector is built from material that ought to survive a rebuild, but no second build was compared. Deploy safety is not established." };
  }
  if (crossBuildEvidence.sameBuild) {
    return { ...base, verdict: "unproven", proven: false,
      note: "Both captures came from the same build. Agreement between them shows determinism, not deploy safety." };
  }
  if (!crossBuildEvidence.matched) {
    return { ...base, verdict: "rejected", proven: false,
      note: "A different build was compared and the selector did not survive it." };
  }
  return { ...base, verdict: "proven", proven: true,
    note: `Survived a build in which generated identifiers changed (${crossBuildEvidence.method}).` };
}
